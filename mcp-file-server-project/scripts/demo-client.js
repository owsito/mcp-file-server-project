import 'dotenv/config';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';

const PROJECT_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const WORKSPACE = path.join(PROJECT_ROOT, 'workspace');
const TRANSCRIPT_PATH = path.join(PROJECT_ROOT, 'docs', 'DEMO_TRANSCRIPT.md');
const MCP_URL = process.env.MCP_URL || 'http://127.0.0.1:3000/mcp';
const TOKEN = process.env.MCP_AUTH_TOKEN || '';
const transcript = [];

if (!TOKEN || TOKEN.length < 24) {
  console.error('Set MCP_AUTH_TOKEN in .env to a token of at least 24 characters.');
  process.exit(1);
}

function clip(value, max = 1600) {
  const text = typeof value === 'string' ? value : JSON.stringify(value, null, 2);
  return text.length > max ? text.slice(0, max) + '\n… [output clipped in transcript]' : text;
}

function record(session, tool, args, result) {
  const content = (result.content || []).map((item) => item.text ?? `[${item.type}]`).join('\n');
  transcript.push(`### ${session} — \`${tool}\`\n\n**Arguments**\n\n\`\`\`json\n${JSON.stringify(args, null, 2)}\n\`\`\`\n\n**Result**\n\n\`\`\`text\n${clip(content)}\n\`\`\`\n`);
  if (result.isError) throw new Error(`${session}: tool ${tool} failed: ${content}`);
  return content;
}

async function openClient(name) {
  const client = new Client({ name, version: '1.0.0' }, { capabilities: {} });
  const transport = new StreamableHTTPClientTransport(new URL(MCP_URL), {
    requestInit: { headers: { Authorization: `Bearer ${TOKEN}` } }
  });
  await client.connect(transport);
  return { client, transport };
}

async function call(session, client, name, args = {}) {
  const result = await client.callTool({ name, arguments: args });
  record(session, name, args, result);
  return result;
}

async function closeClient(connection) {
  if (!connection) return;
  try { await connection.client.close(); } catch {}
  try { await connection.transport.close(); } catch {}
}

function initGitWorkspaceIfNeeded() {
  try {
    execFileSync('git', ['-C', WORKSPACE, 'rev-parse', '--is-inside-work-tree'], { stdio: 'ignore' });
  } catch {
    execFileSync('git', ['-C', WORKSPACE, 'init'], { stdio: 'ignore' });
  }
  try {
    execFileSync('git', ['-C', WORKSPACE, 'rev-parse', '--verify', 'HEAD'], { stdio: 'ignore' });
  } catch {
    execFileSync('git', ['-C', WORKSPACE, 'add', '--all'], { stdio: 'ignore' });
    execFileSync('git', ['-C', WORKSPACE, '-c', 'user.name=Student Demo', '-c', 'user.email=student-demo@example.invalid', 'commit', '-m', 'Baseline Task Utils workspace'], { stdio: 'ignore' });
  }
}

async function main() {
  try {
    const health = await fetch(MCP_URL.replace(/\/mcp\/?$/, '/health'));
    if (!health.ok) throw new Error(`Server health check failed with HTTP ${health.status}.`);
  } catch (error) {
    console.error(`Cannot reach ${MCP_URL}. Start the MCP server first. Details: ${error.message}`);
    process.exit(1);
  }

  initGitWorkspaceIfNeeded();
  transcript.push('# MCP File Server — Two-Session Demonstration Transcript\n\n' +
    `Generated: ${new Date().toISOString()}\n\n` +
    `Endpoint: \`${MCP_URL}\`\n\n` +
    'This transcript is generated by two separate MCP client connections. It verifies that files written by Session 1 are visible to Session 2 and that tool calls can continue work. For the instructor’s “two agent sessions” requirement, pair this protocol-level transcript with a live demonstration in two actual AI-client conversations connected to the same server.\n');

  let session1;
  let session2;
  try {
    const s1 = 'Client Session 1';
    session1 = await openClient('mcp-demo-session-1');
    await call(s1, session1.client, 'list_files', { path: '.' });
    await call(s1, session1.client, 'read_file', { path: 'src/task-utils.js' });
    await call(s1, session1.client, 'read_file', { path: 'tests/task-utils.test.js' });
    await call(s1, session1.client, 'read_file', { path: 'PROJECT_STATE.md' });

    const state1 = `# Project State\n\n## Project\nTask Utils extension — MCP multi-session handoff demonstration.\n\n## Current status\nSession 1 reviewed the source and baseline tests. The overdue-task helper is not implemented yet.\n\n## Goal\nAdd \`getOverdueTasks(tasks, today)\` to \`src/task-utils.js\`. It should return tasks whose \`dueDate\` is earlier than \`today\` and whose status is not \`done\`. The date format is \`YYYY-MM-DD\`.\n\n## Handoff for Session 2\n1. Read this file, \`PLAN_LOG.md\`, \`CHECKPOINTS.md\`, and \`DECISIONS.md\`.\n2. Add the helper next to the existing utility functions.\n3. Add tests for an overdue open task, a not-yet-due task, and an overdue completed task.\n4. Run the workspace tests, inspect Git status/diff, and update all handoff files.\n\n## Constraints\nOnly edit files inside this MCP workspace. Do not use absolute paths. Completed tasks must not be returned.\n`;
    await call(s1, session1.client, 'write_file', { path: 'PROJECT_STATE.md', content: state1, overwrite: true });
    await call(s1, session1.client, 'write_file', { path: 'PLAN_LOG.md', content: '# Plan Log\n\n- [x] Session 1 reviewed `src/task-utils.js` and the baseline tests.\n- [x] Handoff goal and constraints saved in `PROJECT_STATE.md`.\n- [ ] Session 2 implements `getOverdueTasks(tasks, today)`.\n- [ ] Session 2 adds and runs tests.\n- [ ] Review Git status/diff and finalize all handoff files.\n', overwrite: true });
    await call(s1, session1.client, 'write_file', { path: 'CHECKPOINTS.md', content: '# Checkpoints\n\n- [x] Workspace and baseline Task Utils files created.\n- [x] Session 1 inspection completed and handoff state saved.\n- [ ] Overdue helper implemented.\n- [ ] New overdue-task tests pass.\n- [ ] Git diff reviewed and all handoff files updated.\n', overwrite: true });
    await call(s1, session1.client, 'write_file', { path: 'DECISIONS.md', content: '# Decisions\n\n- **Date format:** compare ISO-style `YYYY-MM-DD` strings to keep comparisons deterministic when callers use that format.\n- **Completed tasks:** exclude `status === "done"` even when the due date is in the past.\n- **Safe workspace:** every file operation stays inside the configured workspace root.\n- **Testing:** use the built-in Node.js test runner and avoid extra testing dependencies.\n- **Handoff:** Session 2 must read the shared state files rather than rely on Session 1 conversation history.\n', overwrite: true });
    await closeClient(session1);
    session1 = null;

    const s2 = 'Client Session 2';
    session2 = await openClient('mcp-demo-session-2');
    await call(s2, session2.client, 'read_file', { path: 'PROJECT_STATE.md' });
    await call(s2, session2.client, 'read_file', { path: 'PLAN_LOG.md' });
    await call(s2, session2.client, 'read_file', { path: 'CHECKPOINTS.md' });
    await call(s2, session2.client, 'read_file', { path: 'DECISIONS.md' });

    const originalAnchor = 'export function countByStatus(tasks) {';
    const helper = `export function getOverdueTasks(tasks, today = new Date().toISOString().slice(0, 10)) {\n  return tasks.filter((task) =>\n    task.status !== 'done' &&\n    typeof task.dueDate === 'string' &&\n    task.dueDate < today\n  );\n}\n\n${originalAnchor}`;
    await call(s2, session2.client, 'str_replace', { path: 'src/task-utils.js', oldText: originalAnchor, newText: helper });

    const addedTest = `import test from 'node:test';\nimport assert from 'node:assert/strict';\nimport { getOverdueTasks } from '../src/task-utils.js';\n\ntest('getOverdueTasks returns overdue unfinished tasks but excludes completed and future tasks', () => {\n  const tasks = [\n    { title: 'Past open task', status: 'open', dueDate: '2026-10-10' },\n    { title: 'Due tomorrow', status: 'open', dueDate: '2026-10-16' },\n    { title: 'Past completed task', status: 'done', dueDate: '2026-10-01' },\n    { title: 'No due date', status: 'open' }\n  ];\n  assert.deepEqual(\n    getOverdueTasks(tasks, '2026-10-15').map((task) => task.title),\n    ['Past open task']\n  );\n});\n`;
    await call(s2, session2.client, 'write_file', { path: 'tests/overdue.test.js', content: addedTest, overwrite: false });

    const result = execFileSync(process.execPath, ['--test', 'workspace/tests'], {
      cwd: PROJECT_ROOT,
      encoding: 'utf8',
      timeout: 30_000,
      stdio: ['ignore', 'pipe', 'pipe']
    });
    transcript.push('## Local test execution (run after Client Session 2)\n\n```text\n' + result.trim() + '\n```\n');

    const state2 = `# Project State\n\n## Project\nTask Utils extension — MCP multi-session handoff demonstration.\n\n## Current status\nComplete. Session 2 implemented and tested the overdue-task helper after reading the shared handoff files from Session 1.\n\n## Completed change\nAdded \`getOverdueTasks(tasks, today)\` to \`src/task-utils.js\`. It returns tasks with a \`YYYY-MM-DD\` due date earlier than the requested date, excluding tasks with \`status === "done"\`. The default comparison date is today's date.\n\n## Verification\nThe workspace test suite passed after the helper and new overdue-task test were added.\n\n## Next steps for the live class demo\nConnect two actual AI-client conversations to the same MCP endpoint. In conversation 1, inspect the code and ask the model to save the plan into the handoff files. In conversation 2, ask it to read \`PROJECT_STATE.md\` and continue the task.\n`;
    await call(s2, session2.client, 'write_file', { path: 'PROJECT_STATE.md', content: state2, overwrite: true });
    await call(s2, session2.client, 'write_file', { path: 'PLAN_LOG.md', content: '# Plan Log\n\n- [x] Session 1 reviewed the source and baseline tests.\n- [x] Shared handoff instructions saved.\n- [x] Session 2 read all four handoff files before editing.\n- [x] Added `getOverdueTasks(tasks, today)` with completed-task exclusion.\n- [x] Added tests for overdue, future, completed, and missing-date tasks.\n- [x] Workspace test suite passed.\n- [x] Git status and diff inspected.\n', overwrite: true });
    await call(s2, session2.client, 'write_file', { path: 'CHECKPOINTS.md', content: '# Checkpoints\n\n- [x] Workspace and baseline Task Utils files created.\n- [x] Session 1 inspection and handoff completed.\n- [x] Overdue helper implemented.\n- [x] Overdue-task tests pass.\n- [x] Git diff reviewed and all handoff files updated.\n', overwrite: true });
    await call(s2, session2.client, 'write_file', { path: 'DECISIONS.md', content: '# Decisions\n\n- **Date format:** compare ISO-style `YYYY-MM-DD` strings to keep comparisons deterministic when callers use that format.\n- **Completed tasks:** exclude `status === "done"` even when the due date is in the past.\n- **Safe workspace:** every file operation stays inside the configured workspace root.\n- **Testing:** use Node.js built-in tests; the added test covers overdue, future, completed, and missing-date cases.\n- **Handoff:** Session 2 read persistent shared files before continuing, demonstrating cross-session continuity.\n', overwrite: true });

    await call(s2, session2.client, 'read_file', { path: 'src/task-utils.js' });
    await call(s2, session2.client, 'search_files', { query: 'getOverdueTasks', path: '.', maxResults: 10 });
    await call(s2, session2.client, 'git_status', {});
    await call(s2, session2.client, 'git_diff', { path: 'src/task-utils.js' });
  } finally {
    await closeClient(session1);
    await closeClient(session2);
  }

  await fs.mkdir(path.dirname(TRANSCRIPT_PATH), { recursive: true });
  await fs.writeFile(TRANSCRIPT_PATH, transcript.join('\n'), 'utf8');
  console.log(`Demo complete. Transcript written to ${path.relative(PROJECT_ROOT, TRANSCRIPT_PATH)}.`);
  console.log('The transcript uses two independent MCP client connections; use two actual AI-client conversations for the live agent-session requirement.');
}

main().catch((error) => {
  console.error(error?.stack || error?.message || error);
  process.exit(1);
});
